// Compiles contracts/DisasterReliefFund.sol with the settings the build guide uses in Remix:
// Solidity 0.8.30, optimizer on with 200 runs, EVM target Paris, compilation through IR off.
// It writes the ABI and bytecode the app needs into src/contract/artifact.ts.
//
//   npm run compile           compile and write the artifact
//   npm run compile -- --check   recompile only if the contract source changed
//
// The compiler is the official solc-js package (WebAssembly), so this works on Windows, macOS
// and Linux, on Intel and ARM, with no download at compile time.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import solc from "solc";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCES = {
  "contracts/DisasterReliefFund.sol": "DisasterReliefFund",
  // Helper contracts used only by the automated tests (a recipient that refuses ETH and one that
  // tries to call withdraw() again while it is being paid). The app never deploys them.
  "contracts/test-helpers/RejectingRecipient.sol": "RejectingRecipient",
  "contracts/test-helpers/ReentrantRecipient.sol": "ReentrantRecipient",
};
export const SETTINGS = {
  optimizer: { enabled: true, runs: 200 },
  evmVersion: "paris",
  viaIR: false,
  outputSelection: { "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"] } },
};
const outFile = path.join(root, "src", "contract", "artifact.ts");

const read = (rel) => readFileSync(path.join(root, rel), "utf8").replace(/\r\n/g, "\n");

/** SHA-256 over every source file, with Windows line endings normalised first. */
export function sourceHash() {
  const h = createHash("sha256");
  for (const rel of Object.keys(SOURCES)) h.update(rel).update("\0").update(read(rel));
  return h.digest("hex");
}

function storedHash() {
  if (!existsSync(outFile)) return null;
  return /export const sourceHash = "([0-9a-f]{64})"/.exec(readFileSync(outFile, "utf8"))?.[1] ?? null;
}

function compile() {
  const input = {
    language: "Solidity",
    sources: Object.fromEntries(Object.keys(SOURCES).map((rel) => [rel, { content: read(rel) }])),
    settings: SETTINGS,
  };
  const output = JSON.parse(solc.compile(JSON.stringify(input)));
  const problems = (output.errors ?? []).filter((e) => e.severity === "error");
  for (const e of output.errors ?? []) console.error(e.formattedMessage);
  if (problems.length) throw new Error(`Compilation failed with ${problems.length} error(s).`);

  const version = solc.version();
  if (!version.startsWith("0.8.30+")) throw new Error(`Expected solc 0.8.30, got ${version}`);

  const contracts = {};
  for (const [rel, name] of Object.entries(SOURCES)) {
    const c = output.contracts[rel][name];
    contracts[name] = { abi: c.abi, bytecode: `0x${c.evm.bytecode.object}` };
  }
  return { version, contracts };
}

function write({ version, contracts }) {
  mkdirSync(path.dirname(outFile), { recursive: true });
  const main = contracts.DisasterReliefFund;
  const lines = [
    "// Generated by scripts/compile.mjs from contracts/*.sol. Do not edit by hand:",
    "// change the contract, then run  npm run compile",
    `// Compiler: solc ${version}, optimizer on (200 runs), EVM target paris, via IR off.`,
    `export const sourceHash = "${sourceHash()}";`,
    `export const compilerVersion = ${JSON.stringify(version)};`,
    `export const contractSource = ${JSON.stringify(read("contracts/DisasterReliefFund.sol"))};`,
    `export const fundAbi = ${JSON.stringify(main.abi, null, 2)} as const;`,
    `export const fundBytecode = "${main.bytecode}" as const;`,
  ];
  for (const name of ["RejectingRecipient", "ReentrantRecipient"]) {
    const c = contracts[name];
    const id = name[0].toLowerCase() + name.slice(1);
    lines.push(`export const ${id}Abi = ${JSON.stringify(c.abi)} as const;`);
    lines.push(`export const ${id}Bytecode = "${c.bytecode}" as const;`);
  }
  writeFileSync(outFile, lines.join("\n") + "\n");
  console.log(
    `Compiled with solc ${version}: DisasterReliefFund is ${(main.bytecode.length - 2) / 2} bytes of creation code. Wrote src/contract/artifact.ts`,
  );
}

const runAsScript = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;

if (!runAsScript) {
  // imported for SETTINGS or sourceHash: do nothing else
} else if (process.argv.includes("--check")) {
  if (storedHash() !== sourceHash()) {
    console.log("The contract changed since the last compile; compiling again.");
    write(compile());
  } else {
    console.log("src/contract/artifact.ts matches the contract source.");
  }
} else {
  write(compile());
}
